# Exercicio 8 - Una duas listas com +; faça um slice com os três primeiros elementos; percorra com for

lista1 = [1,2,3]
lista2 = [4,5,6]

# concatenando listas
listas = lista1 + lista2
print(listas)

# slicing
print(listas[0:3])

# Percorrendo com for
for numero in listas:
    print(numero)

for numero in listas[0:3]:
    print(numero)