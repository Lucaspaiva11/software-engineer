# Exercicio 5 - Analise diferentes entradas ("42", "3.5", "abc", "True") e determine quais podem ser convertidas por int(), float() e str(), justificando sua resposta.

# "42" -> Int, por que é um numero sem parte decimal
# "3.5" -> Float, por que é um numero com parte decimal
# "abc" -> String, por que é texto(caracteres)
# "True" -> Boolean, por que é o valor True