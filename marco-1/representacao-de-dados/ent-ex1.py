# Exercicio 1 - Crie uma calculadora simples que leia dois números e exiba as quatro operações básicas.

num1 = int(input("Digite um número: "))
num2 = int(input("Digite outro número: "))

soma = num1+num2
print("Resultado soma: ", soma)
subtracao = num1-num2
print("Resultado subtração: ", subtracao)
multiplicacao = num1*num2
print("Resultado multiplicacao: ", multiplicacao)
divisao = num1/num2
print("Resultado divisao: ", divisao)
